// C %g layout with exact requested significant digits, generated by Ryu.
// Above 1074 significant digits binary64 has no remaining nonzero digits;
// removing trailing zeros makes that clamp equivalent even for huge precision.
size_t General(double value,int precision,char* out){
    uint64_t bits;memcpy(&bits,&value,8);size_t used=0;
    const bool sign=(bits>>63)!=0;
    if(sign)out[used++]='-';
    if(!Finite(value)){
        const char* word=(bits&0xfffffffffffffull)?"nan":"inf";memcpy(out+used,word,3);return used+3;
    }
    int sig=precision<0?6:precision==0?1:precision;if(sig>1074)sig=1074;
    char scientific[1100],digits[1100];const int n=d2exp_buffered_n(value,uint32_t(sig-1),scientific);
    int at=sign?1:0;size_t count=0;
    while(at<n&&scientific[at]!='e'){if(scientific[at]!='.')digits[count++]=scientific[at];++at;}
    ++at;const bool negative=scientific[at++]=='-';int exponent=0;
    while(at<n)exponent=exponent*10+(scientific[at++]-'0');
    if(negative)exponent=-exponent;
    while(count>1&&digits[count-1]=='0')--count;
    if(exponent< -4||exponent>=sig){
        out[used++]=digits[0];if(count>1){out[used++]='.';memcpy(out+used,digits+1,count-1);used+=count-1;}
        out[used++]='e';out[used++]=exponent<0?'-':'+';unsigned magnitude=unsigned(exponent<0?-exponent:exponent);
        if(magnitude>=100)out[used++]=char('0'+magnitude/100);
        out[used++]=char('0'+magnitude/10%10);out[used++]=char('0'+magnitude%10);
    }else{
        const int point=exponent+1;
        if(point<=0){out[used++]='0';out[used++]='.';for(int i=0;i< -point;++i)out[used++]='0';memcpy(out+used,digits,count);used+=count;}
        else{
            for(size_t i=0;i<count||int(i)<point;++i){if(int(i)==point)out[used++]='.';out[used++]=i<count?digits[i]:'0';}
        }
    }
    return used;
}
